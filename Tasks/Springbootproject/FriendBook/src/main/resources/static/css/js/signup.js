$(document).ready(function () {
    const signupForm = $('#signupForm');
    const messageDiv = $('#message');

    signupForm.on('submit', function (e) {
        e.preventDefault();

        // Clear previous messages
        messageDiv.empty();

        // Your reCaptcha v3 Site Key
        const siteKey = '6LfxnY0sAAAAAAHD5n738xWvgiNERN--S1dFgdaR';

        // 1. Request token from Google v3
        grecaptcha.ready(function () {
            grecaptcha.execute(siteKey, { action: 'signup' }).then(function (token) {

                // 2. Collect Form Data
                const formData = {
                    fullName: $('#fullName').val(),
                    email: $('#email').val(),
                    password: $('#password').val(),
                    captchaToken: token // Token generated by v3
                };

                // 3. AJAX Call to Spring Boot
                $.ajax({
                    url: '/auth/signup',
                    type: 'POST',
                    contentType: 'application/json',
                    data: JSON.stringify(formData),
                    beforeSend: function() {
                        // Disable button to prevent double clicks
                        signupForm.find('button').prop('disabled', true).text('Processing...');
                    },
                    success: function (response) {
                        // Response is your SignupResponse DTO
                        messageDiv.html(`<div class="alert alert-success">${response.message}</div>`);

                        // Redirect to login after 2 seconds
                        setTimeout(() => {
                            window.location.href = '/login';
                        }, 1500);
                    },
                    error: function (xhr) {
                        signupForm.find('button').prop('disabled', false).text('Signup');
                        let errorMsg = "An error occurred. Please try again.";
                        if (xhr.responseJSON && xhr.responseJSON.message) {
                            errorMsg = xhr.responseJSON.message;
                        }
                        messageDiv.html(`<div class="alert alert-danger">${errorMsg}</div>`);
                    }
                });
            });
        });
    });
});